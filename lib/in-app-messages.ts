import "server-only";

import db from "@/lib/db";

export async function ensureInAppMessages() {
  await db.execute(`CREATE TABLE IF NOT EXISTS in_app_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    type varchar(50) NOT NULL,
    title varchar(180) NOT NULL,
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
}

export async function createInAppMessage(userId: number, type: string, title: string, body: string) {
  await ensureInAppMessages();
  await db.execute("INSERT INTO in_app_messages (user_id,type,title,body) VALUES (?,?,?,?)", [userId, type, title, body]);
}
