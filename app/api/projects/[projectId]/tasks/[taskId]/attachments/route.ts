import { randomUUID } from "crypto";
import { mkdir, writeFile } from "fs/promises";
import path from "path";
import { NextResponse } from "next/server";
import type { DbResult, DbRow } from "@/lib/db";
import db from "@/lib/db";
import {
  getTaskAttachmentUrl,
  isMinioConfigured,
  uploadTaskAttachment,
} from "@/lib/minio-storage";
import { recordTaskActivity } from "@/lib/task-activities";
import { canChatOnTask } from "@/lib/project-access";
import { getSessionUserId } from "@/lib/session";
import {
  MAX_TASK_ATTACHMENT_BYTES,
  MAX_TASK_ATTACHMENTS_PER_UPLOAD,
  TASK_ATTACHMENT_DIR,
  TASK_ATTACHMENT_ROUTE,
  taskAttachmentContentType,
} from "@/lib/task-attachment-files";

export const dynamic = "force-dynamic";

type TaskRow = DbRow & {
  id: number;
};

type UserRow = DbRow & {
  name: string;
};

async function ensureTaskAttachmentsTable() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS task_attachments (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      task_id integer NOT NULL,
      uploaded_by integer NULL,
      original_name varchar(255) NOT NULL,
      stored_name varchar(255) NOT NULL,
      mime_type varchar(120) NOT NULL,
      file_size integer NOT NULL DEFAULT 0,
      file_url varchar(500) NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
}

export async function POST(
  request: Request,
  context: { params: Promise<{ projectId: string; taskId: string }> },
) {
  const { projectId, taskId } = await context.params;
  const userId = await getSessionUserId() || null;

  if (!userId) {
    return NextResponse.json(
      { error: "Silakan login terlebih dahulu." },
      { status: 401 },
    );
  }

  const [tasks] = await db.query<TaskRow[]>(
    `SELECT id FROM tasks WHERE id = ? AND project_id = ? LIMIT 1`,
    [taskId, projectId],
  );

  if (!tasks.length) {
    return NextResponse.json(
      { error: "Task tidak ditemukan." },
      { status: 404 },
    );
  }

  if (!(await canChatOnTask(projectId, taskId, userId))) {
    return NextResponse.json(
      { error: "Hanya owner project dan assignee task yang dapat mengunggah file." },
      { status: 403 },
    );
  }

  // Checked before buffering the body; per-file sizes are checked again below.
  const declaredSize = Number(request.headers.get("content-length") ?? 0);
  if (declaredSize > MAX_TASK_ATTACHMENT_BYTES * MAX_TASK_ATTACHMENTS_PER_UPLOAD + 1024 * 1024) {
    return NextResponse.json(
      { error: "Ukuran file maksimal 25 MB." },
      { status: 413 },
    );
  }

  const formData = await request.formData();
  const files = formData
    .getAll("files")
    .filter((value): value is File => value instanceof File && value.size > 0);

  if (!files.length) {
    return NextResponse.json(
      { error: "File belum dipilih." },
      { status: 400 },
    );
  }

  if (files.length > MAX_TASK_ATTACHMENTS_PER_UPLOAD) {
    return NextResponse.json(
      { error: `Maksimal ${MAX_TASK_ATTACHMENTS_PER_UPLOAD} file sekali unggah.` },
      { status: 400 },
    );
  }

  const unsupportedFile = files.find((file) => !taskAttachmentContentType(file.name));

  if (unsupportedFile) {
    return NextResponse.json(
      {
        error: `Tipe file "${sanitizeFilename(unsupportedFile.name)}" tidak didukung. Gunakan gambar, PDF, dokumen Office, CSV/TXT, ZIP, atau video/audio.`,
      },
      { status: 400 },
    );
  }

  if (files.some((file) => file.size > MAX_TASK_ATTACHMENT_BYTES)) {
    return NextResponse.json(
      { error: "Ukuran file maksimal 25 MB." },
      { status: 400 },
    );
  }

  await ensureTaskAttachmentsTable();
  const useMinio = isMinioConfigured();

  if (!useMinio) {
    await mkdir(TASK_ATTACHMENT_DIR, { recursive: true });
  }

  let users: UserRow[] = [];

  if (userId) {
    const [userRows] = await db.query<UserRow[]>(
      `SELECT name FROM users WHERE id = ? LIMIT 1`,
      [userId],
    );
    users = userRows;
  }
  const author = users[0]?.name ? getInitials(users[0].name) : "U";
  const attachments = [];

  for (const file of files) {
    const originalName = sanitizeFilename(file.name || "attachment");
    const extension = path.extname(originalName).toLowerCase();
    const contentType = taskAttachmentContentType(originalName) ?? "application/octet-stream";
    const storedName = `${randomUUID()}${extension}`;
    const fileUrl = `${TASK_ATTACHMENT_ROUTE}${storedName}`;
    const arrayBuffer = await file.arrayBuffer();
    const contents = Buffer.from(arrayBuffer);
    let responseUrl = fileUrl;

    if (useMinio) {
      try {
        await uploadTaskAttachment(storedName, contents, contentType);
        responseUrl = await getTaskAttachmentUrl(storedName);
      } catch (error) {
        console.error("Gagal mengunggah attachment ke MinIO:", error);
        return NextResponse.json(
          {
            error:
              "Upload ke MinIO gagal. Periksa endpoint, port, access key, dan secret key.",
          },
          { status: 502 },
        );
      }
    } else {
      await writeFile(path.join(TASK_ATTACHMENT_DIR, storedName), contents);
    }

    const [result] = await db.execute<DbResult>(
      `INSERT INTO task_attachments
        (task_id, uploaded_by, original_name, stored_name, mime_type, file_size, file_url)
       VALUES (?, ?, ?, ?, ?, ?, ?)
       RETURNING id`,
      [
        taskId,
        userId,
        originalName,
        storedName,
        contentType,
        file.size,
        fileUrl,
      ],
    );

    attachments.push({
      id: result.insertId,
      name: originalName,
      url: responseUrl,
      type: contentType,
      size: file.size,
      createdAt: new Date().toISOString(),
      author,
    });

    await recordTaskActivity({
      taskId: Number(taskId),
      userId,
      type: "attachment",
      message: `attached “${originalName}”`,
      relatedId: result.insertId,
    });
  }

  return NextResponse.json({ attachments }, { status: 201 });
}

function sanitizeFilename(filename: string) {
  return filename.replace(/[^\w.\- ]+/g, "").trim().slice(0, 180) || "attachment";
}

function getInitials(name: string) {
  return name
    .split(" ")
    .map((part) => part[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();
}
