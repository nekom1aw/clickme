export const dynamic = "force-dynamic";

type StatusRow = DbRow & {
  id: number;
  name: string;
  color: string;
};

type ProjectRow = DbRow & {
  workspace_id: number;
};

type ProjectNotificationRow = DbRow & {
  project_name: string;
  workspace_name: string;
};

type TagRow = DbRow & {
  id: number;
  name: string;
};

type TaskSnapshotRow = DbRow & {
  name: string;
  description: string | null;
  start_date: Date | string | null;
  due_date: Date | string | null;
  priority: string | null;
  status_id: number;
  status_name: string;
};

function formatActivityDate(value: Date | string | null) {
  if (!value) {
    return "empty";
  }

  const date = value instanceof Date ? value : new Date(value);

  if (Number.isNaN(date.getTime())) {
    return String(value);
  }

  return new Intl.DateTimeFormat("en", {
    month: "short",
    day: "numeric",
    year: "numeric",
  }).format(date);
}

async function ensureTagTables() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS workspace_tags (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      workspace_id integer NOT NULL,
      name citext NOT NULL CHECK (char_length(name) <= 80),
      color varchar(32) NOT NULL DEFAULT 'purple',
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT workspace_tags_workspace_name_unique UNIQUE (workspace_id, name)
    )
  `);

  await db.execute(`
    CREATE TABLE IF NOT EXISTS task_tags (
      task_id integer NOT NULL,
      tag_id integer NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (task_id, tag_id)
    )
  `);
}

async function ensureTaskAssigneesTable() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS task_assignees (
      task_id integer NOT NULL,
      user_id integer NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (task_id, user_id)
    )
  `);
}

async function ensureTaskDescriptionColumn() {
  const [columns] = await db.query<DbRow[]>(
    `SELECT column_name
     FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'tasks'
       AND column_name = 'description'
     LIMIT 1`,
  );

  if (!columns.length) {
    await db.execute(`ALTER TABLE tasks ADD COLUMN description text NULL`);
  }
}

async function ensureTaskStartDateColumn() {
  const [columns] = await db.query<DbRow[]>(
    `SELECT column_name
     FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'tasks'
       AND column_name = 'start_date'
     LIMIT 1`,
  );

  if (!columns.length) {
    await db.execute(`ALTER TABLE tasks ADD COLUMN start_date date NULL`);
  }
}

async function getWorkspaceId(projectId: string) {
  const [projects] = await db.query<ProjectRow[]>(
    `SELECT workspace_id FROM projects WHERE id = ? LIMIT 1`,
    [projectId],
  );

  return Number(projects[0]?.workspace_id ?? 0);
}

async function saveTaskTags(taskId: number, projectId: string, tags: string[]) {
  const workspaceId = await getWorkspaceId(projectId);

  if (!workspaceId) {
    return;
  }

  await ensureTagTables();
  await db.execute(`DELETE FROM task_tags WHERE task_id = ?`, [taskId]);

  // Tags longer than the 80-character column were never linked; skip them instead of failing the request.
  const uniqueTags = [...new Set(tags.map((tag) => tag.trim()).filter((tag) => tag && Array.from(tag).length <= 80))];

  for (const tag of uniqueTags) {
    await db.execute<DbResult>(
      `INSERT INTO workspace_tags (workspace_id, name, color)
       VALUES (?, ?, 'purple')
       ON CONFLICT DO NOTHING`,
      [workspaceId, tag],
    );

    const [rows] = await db.query<TagRow[]>(
      `SELECT id, name FROM workspace_tags WHERE workspace_id = ? AND name = ? LIMIT 1`,
      [workspaceId, tag],
    );
    const tagId = rows[0]?.id;

    if (tagId) {
      await db.execute<DbResult>(
        `INSERT INTO task_tags (task_id, tag_id) VALUES (?, ?) ON CONFLICT DO NOTHING`,
        [taskId, tagId],
      );
    }
  }
}

// Assignees gain access to the task (activity, chat, files), so only project members qualify.
async function allAreProjectMembers(projectId: string, userIds: number[]) {
  const uniqueIds = [...new Set(userIds)];

  if (!uniqueIds.length) {
    return true;
  }

  const [rows] = await db.query<(DbRow & { user_id: number })[]>(
    `SELECT user_id FROM project_members WHERE project_id = ? AND user_id = ANY(?::int[])`,
    [projectId, uniqueIds],
  );

  return rows.length === uniqueIds.length;
}

async function saveTaskAssignees(taskId: number, assigneeIds: number[]) {
  await ensureTaskAssigneesTable();
  await db.execute(`DELETE FROM task_assignees WHERE task_id = ?`, [taskId]);

  const uniqueAssigneeIds = [
    ...new Set(assigneeIds.map((id) => Number(id)).filter(Boolean)),
  ];

  for (const assigneeId of uniqueAssigneeIds) {
    await db.execute<DbResult>(
      `INSERT INTO task_assignees (task_id, user_id) VALUES (?, ?) ON CONFLICT DO NOTHING`,
      [taskId, assigneeId],
    );
  }
}

export async function POST(
  request: Request,
  context: { params: Promise<{ projectId: string }> },
) {
  const { projectId } = await context.params;
  const userId = await getSessionUserId() || null;
  const body = await request.json();
  const name = String(body.name ?? "").trim();
  const statusId = Number(body.statusId ?? 0);
  const assigneeIds = Array.isArray(body.assigneeIds)
    ? body.assigneeIds.map((id: unknown) => Number(id)).filter(Boolean)
    : [];
  const fallbackAssigneeId = Number(body.assigneeId ?? 0) || null;
  const assigneeId = assigneeIds[0] ?? fallbackAssigneeId;
  const startDate = String(body.startDate ?? "").trim() || null;
  const dueDate = String(body.dueDate ?? "").trim() || null;
  const priority = String(body.priority ?? "").trim() || null;
  const description = String(body.description ?? "").trim() || null;
  const tags = Array.isArray(body.tags)
    ? body.tags.map((tag: unknown) => String(tag))
    : [];

  if (!name) {
    return NextResponse.json(
      { error: "Task name wajib diisi." },
      { status: 400 },
    );
  }

  if (!userId) {
    return NextResponse.json(
      { error: "Silakan login terlebih dahulu." },
      { status: 401 },
    );
  }

  if (!(await canManageProject(projectId, userId))) {
    return NextResponse.json(
      { error: "Collaborator tidak dapat membuat task baru." },
      { status: 403 },
    );
  }

  const [statuses] = await db.query<StatusRow[]>(
    `SELECT id, name, color
     FROM project_statuses
     WHERE id = ? AND project_id = ?
     LIMIT 1`,
    [statusId, projectId],
  );

  const status = statuses[0];

  if (!status) {
    return NextResponse.json(
      { error: "Status tidak ditemukan." },
      { status: 404 },
    );
  }

  if (
    !(await allAreProjectMembers(
      projectId,
      assigneeIds.length ? assigneeIds : assigneeId ? [assigneeId] : [],
    ))
  ) {
    return NextResponse.json(
      { error: "Assignee harus anggota project." },
      { status: 400 },
    );
  }

  await ensureTaskDescriptionColumn();
  await ensureTaskStartDateColumn();

  const [result] = await db.execute<DbResult>(
    `INSERT INTO tasks (project_id, status_id, name, assignee_id, start_date, due_date, priority, description)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?)
     RETURNING id`,
    [projectId, statusId, name, assigneeId, startDate, dueDate, priority, description],
  );
  await saveTaskTags(result.insertId, projectId, tags);
  await saveTaskAssignees(
    result.insertId,
    assigneeIds.length ? assigneeIds : assigneeId ? [assigneeId] : [],
  );
  await recordTaskActivity({
    taskId: result.insertId,
    userId,
    type: "created",
    message: "created this task",
  });

  const [projectRows] = await db.query<ProjectNotificationRow[]>(
    `SELECT projects.name AS project_name,
            workspaces.name AS workspace_name
     FROM projects
     INNER JOIN workspaces ON workspaces.id = projects.workspace_id
     WHERE projects.id = ?
     LIMIT 1`,
    [projectId],
  );
  const project = projectRows[0];

  if (project) {
    try {
      await notifyTaskCreatedToWhatsappGroup({
        projectId: Number(projectId),
        taskName: name,
        projectName: project.project_name,
        workspaceName: project.workspace_name,
        description,
        dueDate,
        priority,
        assigneeIds:
          assigneeIds.length > 0
            ? assigneeIds
            : assigneeId
              ? [assigneeId]
              : [],
        tags,
      });
    } catch (error) {
      console.error("Failed to send task notification to WhatsApp:", error);
    }
  }

  return NextResponse.json(
    {
      task: {
        id: result.insertId,
        name,
        description: description ?? "",
        assigneeId,
        assigneeIds: assigneeIds.length
          ? assigneeIds
          : assigneeId
            ? [assigneeId]
            : [],
        assignee: "",
        startDate: startDate ?? "",
        due: "",
        dueDate: dueDate ?? "",
        priority: "",
        tags,
        status: status.name,
        tone: status.color,
      },
    },
    { status: 201 },
  );
}

export async function PATCH(
  request: Request,
  context: { params: Promise<{ projectId: string }> },
) {
  const { projectId } = await context.params;
  const userId = await getSessionUserId() || null;
  const body = await request.json();
  const taskId = Number(body.taskId ?? 0);

  if (!taskId) {
    return NextResponse.json(
      { error: "Task tidak ditemukan." },
      { status: 400 },
    );
  }

  if (!userId) {
    return NextResponse.json(
      { error: "Silakan login terlebih dahulu." },
      { status: 401 },
    );
  }

  await ensureTaskAssigneesTable();
  const taskAccess = await getTaskAccess(projectId, taskId, userId);

  if (!taskAccess.canManage && !taskAccess.isAssigned) {
    return NextResponse.json(
      { error: "Anda hanya dapat mengerjakan task yang ditugaskan kepada Anda." },
      { status: 403 },
    );
  }

  if (
    !taskAccess.canManage &&
    (Object.hasOwn(body, "assigneeId") || Object.hasOwn(body, "assigneeIds"))
  ) {
    return NextResponse.json(
      { error: "Collaborator tidak dapat mengubah assignee task." },
      { status: 403 },
    );
  }

  await ensureTaskStartDateColumn();
  const [taskRows] = await db.query<TaskSnapshotRow[]>(
    `SELECT tasks.name, tasks.description, tasks.start_date, tasks.due_date, tasks.priority,
        tasks.status_id, project_statuses.name AS status_name
     FROM tasks
     INNER JOIN project_statuses ON project_statuses.id = tasks.status_id
     WHERE tasks.id = ? AND tasks.project_id = ?
     LIMIT 1`,
    [taskId, projectId],
  );
  const previousTask = taskRows[0];

  if (!previousTask) {
    return NextResponse.json(
      { error: "Task tidak ditemukan." },
      { status: 404 },
    );
  }

  const updates: string[] = [];
  const values: Array<string | number | null> = [];
  let nextAssigneeIds: number[] | null = null;

  if (Object.hasOwn(body, "startDate")) {
    updates.push("start_date = ?");
    values.push(String(body.startDate ?? "").trim() || null);
  }

  if (Object.hasOwn(body, "name")) {
    const name = String(body.name ?? "").trim();

    if (!name) {
      return NextResponse.json(
        { error: "Task name wajib diisi." },
        { status: 400 },
      );
    }

    updates.push("name = ?");
    values.push(name);
  }

  if (Object.hasOwn(body, "dueDate")) {
    updates.push("due_date = ?");
    values.push(String(body.dueDate ?? "").trim() || null);
  }

  if (Object.hasOwn(body, "priority")) {
    updates.push("priority = ?");
    values.push(String(body.priority ?? "").trim() || null);
  }

  if (Object.hasOwn(body, "description")) {
    await ensureTaskDescriptionColumn();
    updates.push("description = ?");
    values.push(String(body.description ?? "").trim() || null);
  }

  if (Object.hasOwn(body, "assigneeId")) {
    updates.push("assignee_id = ?");
    const assigneeId = Number(body.assigneeId ?? 0) || null;
    values.push(assigneeId);
    nextAssigneeIds = assigneeId ? [assigneeId] : [];
  }

  if (Object.hasOwn(body, "assigneeIds")) {
    const parsedAssigneeIds = Array.isArray(body.assigneeIds)
      ? body.assigneeIds.map((id: unknown) => Number(id)).filter(Boolean)
      : [];
    nextAssigneeIds = parsedAssigneeIds;
    updates.push("assignee_id = ?");
    values.push(parsedAssigneeIds[0] ?? null);
  }

  if (Object.hasOwn(body, "statusId")) {
    const [statusRows] = await db.query<DbRow[]>(
      `SELECT id FROM project_statuses WHERE id = ? AND project_id = ? LIMIT 1`,
      [Number(body.statusId ?? 0), projectId],
    );

    if (!statusRows.length) {
      return NextResponse.json(
        { error: "Status tidak ditemukan." },
        { status: 404 },
      );
    }

    updates.push("status_id = ?");
    values.push(Number(body.statusId ?? 0));
  }

  if (nextAssigneeIds && !(await allAreProjectMembers(projectId, nextAssigneeIds))) {
    return NextResponse.json(
      { error: "Assignee harus anggota project." },
      { status: 400 },
    );
  }

  if (Object.hasOwn(body, "tags")) {
    const tags = Array.isArray(body.tags)
      ? body.tags.map((tag: unknown) => String(tag))
      : [];

    await saveTaskTags(taskId, projectId, tags);
  }

  if (!updates.length && !Object.hasOwn(body, "tags") && nextAssigneeIds === null) {
    return NextResponse.json(
      { error: "Tidak ada data yang diubah." },
      { status: 400 },
    );
  }

  if (updates.length) {
    const [result] = await db.execute<DbResult>(
      `UPDATE tasks
       SET ${updates.join(", ")}
       WHERE id = ? AND project_id = ?`,
      [...values, taskId, projectId],
    );

    if (!result.affectedRows) {
      return NextResponse.json(
        { error: "Task tidak ditemukan." },
        { status: 404 },
      );
    }
  }

  if (nextAssigneeIds !== null) {
    await saveTaskAssignees(taskId, nextAssigneeIds);
  }

  const activities: Array<{
    type: TaskActivityType;
    message: string;
    coalesce?: boolean;
  }> = [];

  if (Object.hasOwn(body, "name")) {
    const nextName = String(body.name ?? "").trim();

    if (nextName && nextName !== previousTask.name) {
      activities.push({
        type: "updated",
        message: `renamed the task from “${previousTask.name}” to “${nextName}”`,
      });
    }
  }

  if (Object.hasOwn(body, "statusId")) {
    const nextStatusId = Number(body.statusId ?? 0);

    if (nextStatusId && nextStatusId !== previousTask.status_id) {
      const [statusRows] = await db.query<StatusRow[]>(
        `SELECT id, name, color
         FROM project_statuses
         WHERE id = ? AND project_id = ?
         LIMIT 1`,
        [nextStatusId, projectId],
      );
      const nextStatus = statusRows[0]?.name ?? "another status";
      activities.push({
        type: "status",
        message: `changed status from ${previousTask.status_name} to ${nextStatus}`,
      });
    }
  }

  if (Object.hasOwn(body, "startDate")) {
    const nextStartDate = String(body.startDate ?? "").trim() || null;
    activities.push({
      type: "date",
      message: nextStartDate
        ? `changed the start date from ${formatActivityDate(previousTask.start_date)} to ${formatActivityDate(nextStartDate)}`
        : "cleared the start date",
    });
  }

  if (Object.hasOwn(body, "dueDate")) {
    const nextDueDate = String(body.dueDate ?? "").trim() || null;
    activities.push({
      type: "date",
      message: nextDueDate
        ? `changed the due date from ${formatActivityDate(previousTask.due_date)} to ${formatActivityDate(nextDueDate)}`
        : "cleared the due date",
    });
  }

  if (Object.hasOwn(body, "priority")) {
    const nextPriority = String(body.priority ?? "").trim();
    activities.push({
      type: "priority",
      message: nextPriority
        ? `changed priority from ${previousTask.priority || "empty"} to ${nextPriority}`
        : "cleared the priority",
    });
  }

  if (Object.hasOwn(body, "description")) {
    const nextDescription = String(body.description ?? "").trim();

    if (nextDescription !== (previousTask.description ?? "").trim()) {
      activities.push({
        type: "description",
        message: nextDescription ? "updated the description" : "cleared the description",
        coalesce: true,
      });
    }
  }

  if (Object.hasOwn(body, "assigneeId") || Object.hasOwn(body, "assigneeIds")) {
    activities.push({
      type: "assignee",
      message:
        nextAssigneeIds?.length || Number(body.assigneeId ?? 0)
          ? "updated the assignees"
          : "cleared the assignees",
    });
  }

  if (Object.hasOwn(body, "tags")) {
    const tags = Array.isArray(body.tags)
      ? body.tags.map((tag: unknown) => String(tag).trim()).filter(Boolean)
      : [];
    activities.push({
      type: "tags",
      message: tags.length ? `updated tags to ${tags.join(", ")}` : "cleared the tags",
    });
  }

  for (const activity of activities) {
    await recordTaskActivity({
      taskId,
      userId,
      ...activity,
    });
  }

  return NextResponse.json({
    task: {
      id: taskId,
    },
  });
}
