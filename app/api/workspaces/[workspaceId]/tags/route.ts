import { NextResponse } from "next/server";
import type { DbResult, DbRow } from "@/lib/db";
import db from "@/lib/db";
import { canAccessWorkspace } from "@/lib/project-access";
import { getSessionUserId } from "@/lib/session";

export const dynamic = "force-dynamic";

type TagRow = DbRow & {
  id: number;
  name: string;
  color: string;
};

async function ensureWorkspaceTagsTable() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS workspace_tags (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      workspace_id integer NOT NULL,
      name citext NOT NULL CHECK (char_length(name) <= 80),
      color varchar(32) NOT NULL DEFAULT 'purple',
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT workspace_tags_workspace_name_unique UNIQUE (workspace_id, name)
    )
  `);
}

export async function GET(
  _request: Request,
  context: { params: Promise<{ workspaceId: string }> },
) {
  const { workspaceId } = await context.params;
  const userId = await getSessionUserId();

  if (!userId) {
    return NextResponse.json(
      { error: "Silakan login terlebih dahulu." },
      { status: 401 },
    );
  }

  if (!(await canAccessWorkspace(workspaceId, userId))) {
    return NextResponse.json(
      { error: "Workspace tidak ditemukan." },
      { status: 404 },
    );
  }


  await ensureWorkspaceTagsTable();

  const [tags] = await db.query<TagRow[]>(
    `SELECT id, name, color
     FROM workspace_tags
     WHERE workspace_id = ?
     ORDER BY name ASC`,
    [workspaceId],
  );

  return NextResponse.json({ tags });
}

export async function POST(
  request: Request,
  context: { params: Promise<{ workspaceId: string }> },
) {
  const { workspaceId } = await context.params;
  const userId = await getSessionUserId();

  if (!userId) {
    return NextResponse.json(
      { error: "Silakan login terlebih dahulu." },
      { status: 401 },
    );
  }

  if (!(await canAccessWorkspace(workspaceId, userId))) {
    return NextResponse.json(
      { error: "Workspace tidak ditemukan." },
      { status: 404 },
    );
  }

  const body = await request.json();
  const name = String(body.name ?? "").trim();
  const color = Array.from(String(body.color ?? "purple").trim() || "purple").slice(0, 32).join("");

  if (!name) {
    return NextResponse.json(
      { error: "Tag name wajib diisi." },
      { status: 400 },
    );
  }

  if (Array.from(name).length > 80) {
    return NextResponse.json(
      { error: "Tag name maksimal 80 karakter." },
      { status: 400 },
    );
  }

  await ensureWorkspaceTagsTable();

  await db.execute<DbResult>(
    `INSERT INTO workspace_tags (workspace_id, name, color)
     VALUES (?, ?, ?)
     ON CONFLICT DO NOTHING`,
    [workspaceId, name, color],
  );

  const [tags] = await db.query<TagRow[]>(
    `SELECT id, name, color
     FROM workspace_tags
     WHERE workspace_id = ? AND name = ?
     LIMIT 1`,
    [workspaceId, name],
  );

  return NextResponse.json({ tag: tags[0] }, { status: 201 });
}
