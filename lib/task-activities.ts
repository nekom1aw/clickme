import type { DbResult, DbRow } from "@/lib/db";
import db from "@/lib/db";

export type TaskActivityType =
  | "created"
  | "updated"
  | "status"
  | "assignee"
  | "date"
  | "priority"
  | "tags"
  | "description"
  | "attachment"
  | "comment";

export async function ensureTaskActivitiesTable() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS task_activities (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      task_id integer NOT NULL,
      user_id integer NULL,
      actor_name varchar(191) NULL,
      activity_type varchar(32) NOT NULL,
      message varchar(500) NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      related_id integer NULL
    )
  `);

  const [relatedIdColumns] = await db.query<DbRow[]>(
    `SELECT column_name
     FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'task_activities'
       AND column_name = 'related_id'
     LIMIT 1`,
  );

  if (!relatedIdColumns.length) {
    await db.execute(`ALTER TABLE task_activities ADD COLUMN related_id integer NULL`);
  }

  const [actorNameColumns] = await db.query<DbRow[]>(
    `SELECT column_name
     FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'task_activities'
       AND column_name = 'actor_name'
     LIMIT 1`,
  );

  if (!actorNameColumns.length) {
    await db.execute(
      `ALTER TABLE task_activities ADD COLUMN actor_name varchar(191) NULL`,
    );
  }
}

export async function recordTaskActivity({
  taskId,
  userId,
  type,
  message,
  actorName = null,
  relatedId = null,
  coalesce = false,
}: {
  taskId: number;
  userId: number | null;
  type: TaskActivityType;
  message: string;
  actorName?: string | null;
  relatedId?: number | null;
  coalesce?: boolean;
}) {
  await ensureTaskActivitiesTable();

  if (coalesce) {
    const [recentRows] = await db.query<(DbRow & { id: number })[]>(
      `SELECT id
       FROM task_activities
       WHERE task_id = ?
         AND activity_type = ?
         AND (user_id IS NOT DISTINCT FROM ?)
         AND created_at >= NOW() - INTERVAL '2 minutes'
       ORDER BY id DESC
       LIMIT 1`,
      [taskId, type, userId],
    );

    if (recentRows[0]) {
      await db.execute(
        `UPDATE task_activities
         SET message = ?, created_at = CURRENT_TIMESTAMP
         WHERE id = ?`,
        [message.slice(0, 500), recentRows[0].id],
      );
      return;
    }
  }

  await db.execute<DbResult>(
    `INSERT INTO task_activities
      (task_id, user_id, actor_name, activity_type, message, related_id)
     VALUES (?, ?, ?, ?, ?, ?)`,
    [
      taskId,
      userId,
      actorName?.trim().slice(0, 191) || null,
      type,
      message.slice(0, 500),
      relatedId,
    ],
  );
}
