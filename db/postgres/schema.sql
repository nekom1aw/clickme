DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'users', 'workspaces', 'projects', 'project_members', 'project_statuses', 'tasks', 'native_forms',
    'data_request_import_sources', 'data_request_import_rows', 'data_request_public_access', 'whatsapp_group_connections'
  ] LOOP
    EXECUTE format(
      'CREATE OR REPLACE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION clickme_touch_updated_at()',
      table_name || '_touch_updated_at', table_name
    );
  END LOOP;
END
$$;
