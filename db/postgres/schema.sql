-- Clickme PostgreSQL schema. Re-runnable: every statement is idempotent.
-- Conventions carried over from the previous MariaDB schema:
--   * flag columns are SMALLINT 0/1 (the app compares them with 1/0);
--   * JSON payloads are TEXT and parsed by the app;
--   * emails, slugs and tag/status names are CITEXT to keep case-insensitive matching;
--   * updated_at is refreshed by trigger only when a row actually changes.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE OR REPLACE FUNCTION clickme_touch_updated_at() RETURNS trigger AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at AND NEW IS DISTINCT FROM OLD THEN
    NEW.updated_at := CURRENT_TIMESTAMP;
  END IF;
  RETURN NEW;
END
$$ LANGUAGE plpgsql;

