import { notFound } from "next/navigation";
import type { DbRow } from "@/lib/db";
import db from "@/lib/db";
import { resolveTaskAttachmentUrl } from "@/lib/minio-storage";
import {
  ensureProjectPermissionSchema,
  type ProjectPermission,
} from "@/lib/project-permissions";
import ProjectWorkspace from "./project-workspace";
import { getSessionUserId } from "@/lib/session";

type ViewMode = "list" | "board" | "timeline";

type ProjectRow = DbRow & {
  id: number;
  workspace_id: number;
  slug: string;
  view_slug: string;
  name: string;
  description: string | null;
  workspace_name: string;
  permission: ProjectPermission;
  is_pinned: number;
};

type StatusRow = DbRow & {
  id: number;
  name: string;
  color: string;
  category: "not_started" | "active" | "closed";
  position: number;
  is_default: number;
};

type TaskRow = DbRow & {
  id: number;
  status_id: number;
  name: string;
  description: string | null;
  start_date: Date | null;
  assignee_id: number | null;
  assignee_name: string | null;
  due_date: Date | null;
  priority: string | null;
};

type TaskTagRow = DbRow & {
  task_id: number;
  name: string;
};

type TaskAssigneeRow = DbRow & {
  task_id: number;
  user_id: number;
  name: string;
};

type TaskAttachmentRow = DbRow & {
  id: number;
  task_id: number;
  original_name: string;
  mime_type: string;
  file_size: number;
  file_url: string;
  stored_name: string;
  created_at: Date;
  author_name: string | null;
};

type ProjectPageProps = {
  projectSlug: string;
  viewSlug?: string;
  viewMode: ViewMode;
};

async function ensureTagTables() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS workspace_tags (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      workspace_id integer NOT NULL,
      name citext NOT NULL CHECK (char_length(name) <= 80),
      color varchar(32) NOT NULL DEFAULT 'purple',
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT workspace_tags_workspace_name_unique UNIQUE (workspace_id, name)
    )
  `);

  await db.execute(`
    CREATE TABLE IF NOT EXISTS task_tags (
      task_id integer NOT NULL,
      tag_id integer NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (task_id, tag_id)
    )
  `);
}

async function ensureTaskAssigneesTable() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS task_assignees (
      task_id integer NOT NULL,
      user_id integer NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (task_id, user_id)
    )
  `);
}

async function ensureTaskDescriptionColumn() {
  const [columns] = await db.query<DbRow[]>(
    `SELECT column_name
     FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'tasks'
       AND column_name = 'description'
     LIMIT 1`,
  );

  if (!columns.length) {
    await db.execute(`ALTER TABLE tasks ADD COLUMN description text NULL`);
  }
}

async function ensureTaskStartDateColumn() {
  const [columns] = await db.query<DbRow[]>(
    `SELECT column_name
     FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'tasks'
       AND column_name = 'start_date'
     LIMIT 1`,
  );

  if (!columns.length) {
    await db.execute(`ALTER TABLE tasks ADD COLUMN start_date date NULL`);
  }
}

async function ensureTaskAttachmentsTable() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS task_attachments (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      task_id integer NOT NULL,
      uploaded_by integer NULL,
      original_name varchar(255) NOT NULL,
      stored_name varchar(255) NOT NULL,
      mime_type varchar(120) NOT NULL,
      file_size integer NOT NULL DEFAULT 0,
      file_url varchar(500) NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
}

function toDateValue(date: Date) {
  const year = date.getFullYear();
  const month = `${date.getMonth() + 1}`.padStart(2, "0");
  const day = `${date.getDate()}`.padStart(2, "0");

  return `${year}-${month}-${day}`;
}

async function getProject(userId: number, projectSlug: string, viewSlug?: string) {
  await ensureProjectPermissionSchema();
  const whereClause = viewSlug
    ? "projects.slug = ? AND projects.view_slug = ? AND (workspaces.owner_id = ? OR project_members.user_id = ?)"
    : "projects.slug = ? AND (workspaces.owner_id = ? OR project_members.user_id = ?)";
  const values = viewSlug
    ? [projectSlug, viewSlug, userId, userId]
    : [projectSlug, userId, userId];
  const [rows] = await db.query<ProjectRow[]>(
    `SELECT projects.id, projects.workspace_id, projects.slug, projects.view_slug, projects.name, projects.description,
        workspaces.name AS workspace_name, COALESCE(project_members.is_pinned, 0) AS is_pinned,
        CASE
          WHEN projects.owner_id = ? OR workspaces.owner_id = ? THEN 'Full akses'
          ELSE project_members.permission
        END AS permission
     FROM projects
     INNER JOIN workspaces ON workspaces.id = projects.workspace_id
     LEFT JOIN project_members ON project_members.project_id = projects.id
       AND project_members.user_id = ?
     WHERE ${whereClause}
     LIMIT 1`,
    [userId, userId, userId, ...values],
  );

  return rows[0];
}

async function getProjectGroups(
  projectId: number,
  userId: number,
  canViewAllTasks: boolean,
) {
  await ensureTagTables();
  await ensureTaskAssigneesTable();
  await ensureTaskDescriptionColumn();
  await ensureTaskStartDateColumn();
  await ensureTaskAttachmentsTable();

  const [statuses] = await db.query<StatusRow[]>(
    `SELECT id, name, color, category, position, is_default
     FROM project_statuses
     WHERE project_id = ?
     ORDER BY COALESCE(array_position(ARRAY['not_started', 'active', 'closed']::text[], category::text), 0), position ASC, id ASC`,
    [projectId],
  );

  const [tasks] = await db.query<TaskRow[]>(
    `SELECT tasks.id, tasks.status_id, tasks.name, tasks.description, tasks.assignee_id, tasks.start_date, tasks.due_date, tasks.priority,
        users.name AS assignee_name
     FROM tasks
     LEFT JOIN users ON users.id = tasks.assignee_id
     WHERE tasks.project_id = ?
       AND (
         ? = 1
         OR tasks.assignee_id = ?
         OR EXISTS (
           SELECT 1
           FROM task_assignees
           WHERE task_assignees.task_id = tasks.id
             AND task_assignees.user_id = ?
         )
       )
     ORDER BY tasks.id ASC`,
    [projectId, canViewAllTasks ? 1 : 0, userId, userId],
  );
  const [taskTags] = await db.query<TaskTagRow[]>(
    `SELECT task_tags.task_id, workspace_tags.name
     FROM task_tags
     INNER JOIN workspace_tags ON workspace_tags.id = task_tags.tag_id
     INNER JOIN tasks ON tasks.id = task_tags.task_id
     WHERE tasks.project_id = ?
     ORDER BY workspace_tags.name ASC`,
    [projectId],
  );
  const [taskAssignees] = await db.query<TaskAssigneeRow[]>(
    `SELECT task_assignees.task_id, task_assignees.user_id, users.name
     FROM task_assignees
     INNER JOIN users ON users.id = task_assignees.user_id
     INNER JOIN tasks ON tasks.id = task_assignees.task_id
     WHERE tasks.project_id = ?
     ORDER BY task_assignees.created_at ASC, task_assignees.user_id ASC`,
    [projectId],
  );
  const [taskAttachments] = await db.query<TaskAttachmentRow[]>(
    `SELECT task_attachments.id, task_attachments.task_id, task_attachments.original_name,
        task_attachments.mime_type, task_attachments.file_size, task_attachments.file_url,
        task_attachments.stored_name,
        task_attachments.created_at, users.name AS author_name
     FROM task_attachments
     INNER JOIN tasks ON tasks.id = task_attachments.task_id
     LEFT JOIN users ON users.id = task_attachments.uploaded_by
     WHERE tasks.project_id = ?
     ORDER BY task_attachments.created_at ASC, task_attachments.id ASC`,
    [projectId],
  );
  const resolvedTaskAttachments = await Promise.all(
    taskAttachments.map(async (attachment) => ({
      ...attachment,
      resolved_url: await resolveTaskAttachmentUrl(
        attachment.file_url,
        attachment.stored_name,
      ),
    })),
  );

  return statuses.map((status) => ({
    id: status.id,
    label: status.name,
    tone: status.color,
    category: status.category,
    isDefault: Boolean(status.is_default),
    tasks: tasks
      .filter((task) => task.status_id === status.id)
      .map((task) => {
        const assignees = taskAssignees.filter(
          (assignee) => assignee.task_id === task.id,
        );
        const fallbackAssignee = task.assignee_id && task.assignee_name
          ? [{ user_id: task.assignee_id, name: task.assignee_name }]
          : [];
        const visibleAssignees = assignees.length ? assignees : fallbackAssignee;

        return {
          id: task.id,
          name: task.name,
          description: task.description ?? "",
          startDate: task.start_date ? toDateValue(task.start_date) : "",
          assigneeId: visibleAssignees[0]?.user_id ?? null,
          assigneeIds: visibleAssignees.map((assignee) => assignee.user_id),
          assignee: visibleAssignees
            .map((assignee) =>
              assignee.name
                .split(" ")
                .map((part) => part[0])
                .join("")
                .slice(0, 2)
                .toUpperCase(),
            )
            .join(","),
          due: task.due_date
            ? new Intl.DateTimeFormat("en", {
                month: "short",
                day: "numeric",
              }).format(task.due_date)
            : "",
          dueDate: task.due_date ? toDateValue(task.due_date) : "",
          priority: task.priority ?? "",
          tags: taskTags
            .filter((tag) => tag.task_id === task.id)
            .map((tag) => tag.name),
          attachments: resolvedTaskAttachments
            .filter((attachment) => attachment.task_id === task.id)
            .map((attachment) => ({
              id: attachment.id,
              name: attachment.original_name,
              url: attachment.resolved_url,
              type: attachment.mime_type,
              size: attachment.file_size,
              createdAt: attachment.created_at.toISOString(),
              author: attachment.author_name
                ? attachment.author_name
                    .split(" ")
                    .map((part) => part[0])
                    .join("")
                    .slice(0, 2)
                    .toUpperCase()
                : "U",
            })),
          status: status.name,
          tone: status.color,
        };
      }),
  }));
}

export default async function ProjectPage({
  projectSlug,
  viewSlug,
  viewMode,
}: ProjectPageProps) {
  const userId = await getSessionUserId();

  if (!userId) {
    notFound();
  }

  const project = await getProject(userId, projectSlug, viewSlug);

  if (!project) {
    notFound();
  }

  const groups = await getProjectGroups(
    project.id,
    userId,
    project.permission === "Full akses" || project.permission === "Manage",
  );

  return (
    <ProjectWorkspace
      projectId={project.id}
      workspaceId={project.workspace_id}
      workspaceName={project.workspace_name}
      projectName={project.name}
      projectSlug={project.slug}
      viewSlug={project.view_slug}
      viewMode={viewMode}
      groups={groups}
      permission={project.permission}
      initialIsPinned={Boolean(project.is_pinned)}
    />
  );
}
