import db from "@/lib/db";
import type { DbConnection, DbRow } from "@/lib/db";
import { ensureProjectPermissionSchema } from "@/lib/project-permissions";
import { sendWorkspaceInvitationEmail } from "@/lib/workspace-invitation-email";
export class InvitationError extends Error {
  status: number;
  constructor(message: string, status = 400) { super(message); this.status = status; }
}
export async function ensureInvitations() {
  await db.execute(`CREATE TABLE IF NOT EXISTS workspace_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id integer NOT NULL,
    email citext NOT NULL CHECK (char_length(email) <= 180), invited_by integer NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN ('administrator', 'manager', 'collaborator')),
    project_ids text NOT NULL, status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined', 'cancelled')),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, responded_at timestamptz NULL,
    CONSTRAINT workspace_invitations_workspace_email UNIQUE (workspace_id, email)
  )`);
}
async function manages(c: DbConnection, workspaceId: number, userId: number) {
  const [rows] = await c.query<DbRow[]>(`SELECT w.id FROM workspaces w WHERE w.id=? AND (w.owner_id=? OR EXISTS
    (SELECT 1 FROM workspace_members m WHERE m.workspace_id=w.id AND m.user_id=? AND m.role='administrator'))`, [workspaceId,userId,userId]);
  return rows.length > 0;
}
export async function inviteWorkspace(workspaceId: number, actor: number, email: string, role: string, projectIds: number[]) {
  if (!actor) throw new InvitationError("Silakan login.",401);
  if (!Number.isSafeInteger(workspaceId) || workspaceId < 1 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) || email.length>180) throw new InvitationError("Masukkan email yang valid.");
  if (!["administrator","manager","collaborator"].includes(role) || projectIds.some(id=>!Number.isSafeInteger(id)||id<1)) throw new InvitationError("Role atau project tidak valid.");
  await ensureInvitations();
  const c=await db.getConnection();
  let invitationDetails: {workspaceName: string; inviterName: string; invitationId: number; projectNames: string[]} | null = null;
  try {
    await c.beginTransaction();
    const [workspace]=await c.query<DbRow[]>("SELECT w.id,w.name,u.name AS inviter_name FROM workspaces w INNER JOIN users u ON u.id=? WHERE w.id=? FOR UPDATE",[actor,workspaceId]);
    if (!workspace.length || !await manages(c,workspaceId,actor)) throw new InvitationError("Tidak punya akses mengundang anggota.",403);
    const [members]=await c.query<DbRow[]>(`SELECT u.id FROM users u WHERE u.email=? AND (
      EXISTS(SELECT 1 FROM workspaces w WHERE w.id=? AND w.owner_id=u.id) OR EXISTS(SELECT 1 FROM workspace_members m WHERE m.workspace_id=? AND m.user_id=u.id))`,[email,workspaceId,workspaceId]);
    if(members.length) throw new InvitationError("Email tersebut sudah menjadi anggota workspace.",409);
    const ids=[...new Set(projectIds)];
    let projectNames: string[]=[];
    if(ids.length){const [projects]=await c.query<DbRow[]>("SELECT id,name FROM projects WHERE workspace_id=? AND id = ANY(?)",[workspaceId,ids]);if(projects.length!==ids.length)throw new InvitationError("Project harus berada di workspace ini.");projectNames=projects.map(project=>String(project.name));}
    const [pending]=await c.query<DbRow[]>("SELECT id FROM workspace_invitations WHERE workspace_id=? AND email=? AND status='pending'",[workspaceId,email]);
    if(pending.length)throw new InvitationError("Undangan untuk email ini masih menunggu jawaban.",409);
    await c.execute(`INSERT INTO workspace_invitations (workspace_id,email,invited_by,role,project_ids) VALUES (?,?,?,?,?)
      ON CONFLICT (workspace_id,email) DO UPDATE SET invited_by=EXCLUDED.invited_by,role=EXCLUDED.role,project_ids=EXCLUDED.project_ids,status='pending',created_at=NOW(),responded_at=NULL`,[workspaceId,email,actor,role,JSON.stringify(ids)]);
    const [invitationRows]=await c.query<DbRow[]>("SELECT id FROM workspace_invitations WHERE workspace_id=? AND email=? LIMIT 1",[workspaceId,email]);
    await c.commit();
    invitationDetails={workspaceName:String(workspace[0].name),inviterName:String(workspace[0].inviter_name),invitationId:Number(invitationRows[0].id),projectNames};
  } catch(error){await c.rollback();throw error;} finally {c.release();}
  let emailNotificationSent=false;
  if(invitationDetails){
    try{emailNotificationSent=await sendWorkspaceInvitationEmail({to:email,workspaceName:invitationDetails.workspaceName,inviterName:invitationDetails.inviterName,role,invitationId:invitationDetails.invitationId,projectNames:invitationDetails.projectNames});}
    catch{emailNotificationSent=false;}
  }
  return {emailNotificationSent};
}
export async function answerInvitation(userId: number, invitationId: number, action: string) {
  if(!userId)throw new InvitationError("Silakan login.",401);
  if(!Number.isSafeInteger(invitationId)||invitationId<1||!["accept","decline"].includes(action))throw new InvitationError("Respons undangan tidak valid.");
  await ensureInvitations(); await ensureProjectPermissionSchema();
  const c=await db.getConnection();
  try{
    await c.beginTransaction();
    const [rows]=await c.query<DbRow[]>(`SELECT i.* FROM workspace_invitations i INNER JOIN users u ON u.email=i.email WHERE i.id=? AND u.id=? FOR UPDATE`,[invitationId,userId]);
    const invitation=rows[0];if(!invitation)throw new InvitationError("Undangan tidak ditemukan.",404);
    if(invitation.status!=="pending")throw new InvitationError("Undangan sudah ditanggapi.",409);
    if(action==="accept"){
      if(!await manages(c,invitation.workspace_id,invitation.invited_by))throw new InvitationError("Pengundang sudah tidak memiliki akses. Minta undangan baru.",403);
      const [existing]=await c.query<DbRow[]>("SELECT user_id FROM workspace_members WHERE workspace_id=? AND user_id=?",[invitation.workspace_id,userId]);
      // Never overwrite roles or project assignments added since the invitation was created.
      if(!existing.length){
        await c.execute("INSERT INTO workspace_members (workspace_id,user_id,role) VALUES (?,?,?)",[invitation.workspace_id,userId,invitation.role]);
        const ids=JSON.parse(invitation.project_ids) as number[];
        if(ids.length){const [projects]=await c.query<DbRow[]>("SELECT id FROM projects WHERE workspace_id=? AND id = ANY(?)",[invitation.workspace_id,ids]);
          for(const project of projects)await c.execute("INSERT INTO project_members (project_id,user_id,permission) VALUES (?,?,?) ON CONFLICT DO NOTHING",[project.id,userId,invitation.role==='administrator'?'Full akses':invitation.role==='manager'?'Manage':'Collaborator']);}
      }
    }
    await c.execute("UPDATE workspace_invitations SET status=?,responded_at=NOW() WHERE id=?",[action==='accept'?'accepted':'declined',invitationId]);
    await c.commit();
  }catch(error){await c.rollback();throw error;}finally{c.release();}
}
export async function removeWorkspaceMember(workspaceId: number, actor: number, userId: number) {
  if(!actor)throw new InvitationError("Silakan login.",401);
  if(!Number.isSafeInteger(userId)||userId<1)throw new InvitationError("Anggota tidak valid.");
  await ensureInvitations();const c=await db.getConnection();
  try{
    await c.beginTransaction();
    const [rows]=await c.query<DbRow[]>("SELECT owner_id FROM workspaces WHERE id=? FOR UPDATE",[workspaceId]);
    if(!rows.length||!await manages(c,workspaceId,actor))throw new InvitationError("Tidak punya akses menghapus anggota.",403);
    if(Number(rows[0].owner_id)===userId)throw new InvitationError("Owner tidak dapat dihapus.");
    const [owned]=await c.query<DbRow[]>("SELECT id FROM projects WHERE workspace_id=? AND owner_id=? LIMIT 1",[workspaceId,userId]);
    if(owned.length)throw new InvitationError("Anggota masih menjadi owner project. Alihkan kepemilikan project terlebih dahulu.");
    await c.execute("DELETE FROM project_members pm USING projects p WHERE p.id=pm.project_id AND p.workspace_id=? AND pm.user_id=?",[workspaceId,userId]);
    await c.execute("DELETE FROM workspace_members WHERE workspace_id=? AND user_id=?",[workspaceId,userId]);
    await c.execute("UPDATE workspace_invitations i SET status='cancelled',responded_at=NOW() FROM users u WHERE u.email=i.email AND i.workspace_id=? AND u.id=? AND i.status='pending'",[workspaceId,userId]);
    await c.commit();
  }catch(error){await c.rollback();throw error;}finally{c.release();}
}
