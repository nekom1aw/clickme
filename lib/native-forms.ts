let schema: Promise<void> | undefined;
export function ensureForms() {
  return (schema ??= (async () => {
    await db.execute(`CREATE TABLE IF NOT EXISTS native_forms (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id integer NULL,
      token varchar(48) NOT NULL CONSTRAINT native_forms_token_key UNIQUE, title varchar(200) NOT NULL, description text NOT NULL,
      fields text NOT NULL, is_published smallint NOT NULL DEFAULT 0,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      owner_id integer NULL, project_id integer NULL, automation text NULL, presentation text NULL, sections text NULL)`);
    const [columns] = await db.query<DbRow[]>(
      "SELECT column_name, data_type, is_nullable FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'native_forms'",
    );
    if (!columns.some((c) => c.column_name === "sections"))
      await db.execute(
        "ALTER TABLE native_forms ADD COLUMN sections text NULL",
      );
    if (!columns.some((c) => c.column_name === "presentation"))
      await db.execute(
        "ALTER TABLE native_forms ADD COLUMN presentation text NULL",
      );
    for (const column of ["owner_id", "project_id"]) {
      if (!columns.some((c) => c.column_name === column))
        await db.execute(
          `ALTER TABLE native_forms ADD COLUMN ${column} integer NULL`,
        );
    }
    if (!columns.some((c) => c.column_name === "automation"))
      await db.execute(
        "ALTER TABLE native_forms ADD COLUMN automation text NULL",
      );
    if (
      columns.some(
        (c) => c.column_name === "workspace_id" && c.is_nullable === "NO",
      )
    )
      await db.execute(
        "ALTER TABLE native_forms ALTER COLUMN workspace_id DROP NOT NULL",
      );
    await db.execute(
      "UPDATE native_forms f SET owner_id = w.owner_id FROM workspaces w WHERE w.id = f.workspace_id AND f.owner_id IS NULL",
    );
    await db.execute(`CREATE TABLE IF NOT EXISTS native_form_responses (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, form_id integer NOT NULL, answers text NOT NULL,
      fields text NOT NULL, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, task_id integer NULL, submission_key varchar(64) NULL,
      CONSTRAINT native_form_responses_form_submission UNIQUE (form_id, submission_key))`);
    const [responseColumns] = await db.query<DbRow[]>(
      "SELECT column_name, data_type, is_nullable FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'native_form_responses'",
    );
    if (!responseColumns.some((c) => c.column_name === "task_id"))
      await db.execute(
        "ALTER TABLE native_form_responses ADD COLUMN task_id integer NULL",
      );
    if (!responseColumns.some((c) => c.column_name === "submission_key"))
      await db.execute(
        "ALTER TABLE native_form_responses ADD COLUMN submission_key varchar(64) NULL, ADD CONSTRAINT native_form_responses_form_submission UNIQUE (form_id, submission_key)",
      );
  })().catch((error) => {
    schema = undefined;
    throw error;
  }));
}
export async function currentFormUser() {
  const id = await getSessionUserId();
  if (!Number.isSafeInteger(id) || id < 1)
    throw new FormError("Silakan login terlebih dahulu.", 401);
  const [users] = await db.query<DbRow[]>(
    "SELECT id FROM users WHERE id = ?",
    [id],
  );
  if (!users.length) throw new FormError("Silakan login terlebih dahulu.", 401);
  return id;
}
export async function formWorkspaces(userId: number) {
  const [rows] = await db.query<DbRow[]>(
    `SELECT w.id, w.name FROM workspaces w
    WHERE w.owner_id = ? OR EXISTS (SELECT 1 FROM workspace_members m WHERE m.workspace_id = w.id AND m.user_id = ? AND m.role IN ('administrator', 'manager')) ORDER BY w.name`,
    [userId, userId],
  );
  return rows as (DbRow & { id: number; name: string })[];
}
export async function requireFormWorkspace(
  workspaceId: number,
  userId: number,
) {
  if (!(await formWorkspaces(userId)).some((w) => w.id === workspaceId))
    throw new FormError("Tidak punya akses mengelola form workspace ini.", 403);
}
export type NativeForm = DbRow & {
  id: number;
  workspace_id: number | null;
  owner_id: number;
  project_id: number | null;
  token: string;
  title: string;
  description: string;
  fields: FormField[] | string;
  automation: FormAutomation | string | null;
  presentation: FormPresentation | string | null;
  sections: FormSection[] | string | null;
  is_published: number;
};
export function decode<T>(value: T | string): T {
  return typeof value === "string" ? JSON.parse(value) : value;
}
export function serializeForm(form: NativeForm) {
  return {
    id: form.id,
    workspaceId: form.workspace_id,
    projectId: form.project_id,
    token: form.token,
    title: form.title,
    description: form.description,
    fields: decode<FormField[]>(form.fields),
    sections: form.sections
      ? decode<FormSection[]>(form.sections)
      : defaultSections(decode<FormField[]>(form.fields)),
    automation: form.automation
      ? decode<FormAutomation>(form.automation)
      : { ...defaultAutomation },
    presentation: form.presentation
      ? decode<FormPresentation>(form.presentation)
      : emptyPresentation(),
    isPublished: Boolean(form.is_published),
  };
}
export async function managedForm(id: string) {
  const userId = await currentFormUser();
  await ensureForms();
  if (!/^\d+$/.test(id) || Number(id) > 2147483647)
    throw new FormError("Form tidak ditemukan.", 404);
  const [rows] = await db.query<NativeForm[]>(
    "SELECT * FROM native_forms WHERE id = ?",
    [id],
  );
  if (!rows[0]) throw new FormError("Form tidak ditemukan.", 404);
  if (rows[0].owner_id !== userId) {
    if (!rows[0].workspace_id)
      throw new FormError("Tidak punya akses form ini.", 403);
    await requireFormWorkspace(rows[0].workspace_id, userId);
  }
  return rows[0];
}
export function formError(error: unknown) {
  if (error instanceof FormError)
    return Response.json({ error: error.message }, { status: error.status });
  if (error instanceof SyntaxError)
    return Response.json({ error: "Data JSON tidak valid." }, { status: 400 });
  console.error("Native forms request failed", error);
  return Response.json(
    { error: "Form tidak dapat diproses. Coba lagi." },
    { status: 500 },
  );
}
export async function formBody(request: Request) {
  const text = await request.text();
  if (text.length > 200000) throw new FormError("Data terlalu besar.", 413);
  const body = JSON.parse(text);
  if (!body || typeof body !== "object" || Array.isArray(body))
    throw new FormError("Data form tidak valid.");
  return body;
}

export async function formProjects(userId: number) {
  const [rows] = await db.query<DbRow[]>(
    `SELECT p.id, p.name, p.workspace_id AS "workspaceId" FROM projects p
    WHERE p.owner_id = ? OR EXISTS (SELECT 1 FROM project_members m WHERE m.project_id = p.id AND m.user_id = ? AND m.permission IN ('Full akses','Manage')) ORDER BY p.name`,
    [userId, userId],
  );
  return rows;
}
export async function validateFormTarget(
  body: Record<string, unknown>,
  userId: number,
) {
  const workspaceId = body.workspaceId ? Number(body.workspaceId) : null;
  const projectId = body.projectId ? Number(body.projectId) : null;
  if (workspaceId) await requireFormWorkspace(workspaceId, userId);
  if (projectId) {
    const project = (await formProjects(userId)).find(
      (p) => p.id === projectId && p.workspaceId === workspaceId,
    );
    if (!project)
      throw new FormError(
        "Project tidak tersedia atau bukan bagian workspace yang dipilih.",
        403,
      );
  }
  return { workspaceId, projectId };
}
