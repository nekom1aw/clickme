import "server-only";

import { createHash, randomBytes } from "node:crypto";
import type { DbResult, DbRow } from "@/lib/db";
import db from "@/lib/db";
import { canManageProject } from "@/lib/project-access";

export type WhatsappScopeType = "workspace" | "project";

type ScopeRow = DbRow & {
  id: number;
  name: string;
};

type WorkspaceAccessRow = DbRow & {
  can_manage: number;
};

type ConnectionRow = DbRow & {
  id: number;
  scope_type: WhatsappScopeType;
  scope_id: number;
  group_chat_id: string | null;
  group_name: string | null;
  connected_at: Date | null;
  connect_code_expires_at: Date | null;
};

export async function ensureWhatsappGroupConnectionSchema() {
  await db.execute(`
    CREATE TABLE IF NOT EXISTS whatsapp_group_connections (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      scope_type varchar(20) NOT NULL CHECK (scope_type IN ('workspace', 'project')),
      scope_id integer NOT NULL,
      connect_code_hash varchar(64) NULL CONSTRAINT unique_whatsapp_connect_code UNIQUE,
      connect_code_expires_at timestamptz NULL,
      group_chat_id varchar(191) NULL,
      group_name varchar(255) NULL,
      connected_at timestamptz NULL,
      created_by integer NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT unique_whatsapp_scope UNIQUE (scope_type, scope_id)
    )
  `);
}

export function hashWhatsappConnectCode(code: string) {
  return createHash("sha256").update(code.trim().toUpperCase()).digest("hex");
}

export function createWhatsappConnectCode() {
  // 64 bits: anyone in any WhatsApp group can send guesses to the bot.
  return `CONNECT-${randomBytes(8).toString("hex").toUpperCase()}`;
}

export async function canManageWhatsappScope(
  scopeType: WhatsappScopeType,
  scopeId: number,
  userId: number,
) {
  if (scopeType === "project") {
    return canManageProject(scopeId, userId);
  }

  const [rows] = await db.query<WorkspaceAccessRow[]>(
    `SELECT EXISTS(
       SELECT 1
       FROM workspaces
       LEFT JOIN workspace_members
         ON workspace_members.workspace_id = workspaces.id
        AND workspace_members.user_id = ?
       WHERE workspaces.id = ?
         AND (
           workspaces.owner_id = ?
           OR workspace_members.role IN ('administrator', 'manager')
         )
     )::int AS can_manage`,
    [userId, scopeId, userId],
  );

  return Boolean(rows[0]?.can_manage);
}

export async function getWhatsappScopeName(
  scopeType: WhatsappScopeType,
  scopeId: number,
) {
  const table = scopeType === "workspace" ? "workspaces" : "projects";
  const [rows] = await db.query<ScopeRow[]>(
    `SELECT id, name FROM ${table} WHERE id = ? LIMIT 1`,
    [scopeId],
  );

  return rows[0]?.name ?? null;
}

export async function getWhatsappGroupConnection(
  scopeType: WhatsappScopeType,
  scopeId: number,
) {
  await ensureWhatsappGroupConnectionSchema();
  const [rows] = await db.query<ConnectionRow[]>(
    `SELECT id, scope_type, scope_id, group_chat_id, group_name,
            connected_at, connect_code_expires_at
     FROM whatsapp_group_connections
     WHERE scope_type = ? AND scope_id = ?
     LIMIT 1`,
    [scopeType, scopeId],
  );

  return rows[0] ?? null;
}

export async function saveWhatsappConnectCode(input: {
  scopeType: WhatsappScopeType;
  scopeId: number;
  userId: number;
  code: string;
}) {
  await ensureWhatsappGroupConnectionSchema();
  const codeHash = hashWhatsappConnectCode(input.code);

  await db.execute<DbResult>(
    `INSERT INTO whatsapp_group_connections
       (scope_type, scope_id, connect_code_hash, connect_code_expires_at,
        group_chat_id, group_name, connected_at, created_by)
     VALUES (?, ?, ?, NOW() + INTERVAL '15 minutes', NULL, NULL, NULL, ?)
     ON CONFLICT (scope_type, scope_id) DO UPDATE SET
       connect_code_hash = EXCLUDED.connect_code_hash,
       connect_code_expires_at = EXCLUDED.connect_code_expires_at,
       group_chat_id = NULL,
       group_name = NULL,
       connected_at = NULL,
       created_by = EXCLUDED.created_by`,
    [input.scopeType, input.scopeId, codeHash, input.userId],
  );
}
