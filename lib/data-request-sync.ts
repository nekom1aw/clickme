export type DataRequestImportInput = { googleSheetUrl?: string; csv?: string; workspaceName?: string; workspaceId?: number };

function randomSlug(name: string, fallback: string) {
  const base =
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "")
      .slice(0, 42) || fallback;
  return `${base}-${randomBytes(4).toString("hex")}`;
}

export async function ensureImportSchema() {
  await ensureSheetSourceSchema();
  await ensureSheetNotificationQueue();
  await db.execute(`
    CREATE TABLE IF NOT EXISTS data_request_import_rows (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      workspace_id integer NOT NULL,
      project_id integer NOT NULL,
      task_id integer NOT NULL,
      source_key varchar(64) NOT NULL,
      source_timestamp timestamptz NULL,
      source_row integer NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT data_request_workspace_source_unique UNIQUE (workspace_id, source_key)
    )
  `);

  await db.execute(`
    CREATE TABLE IF NOT EXISTS data_request_import_sources (
      workspace_id integer PRIMARY KEY,
      google_sheet_url text NOT NULL,
      last_synced_at timestamptz NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);

  const [descriptionColumns] = await db.query<DbRow[]>(
    `SELECT column_name, data_type
     FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'tasks'
       AND column_name = 'description'
     LIMIT 1`,
  );
  if (!descriptionColumns.length) {
    await db.execute(`ALTER TABLE tasks ADD COLUMN description text NULL`);
  } else if (descriptionColumns[0].data_type !== "text") {
    await db.execute(`ALTER TABLE tasks ALTER COLUMN description TYPE text, ALTER COLUMN description DROP NOT NULL`);
  }
}

export async function importDataRequests(
  userId: number,
  body: DataRequestImportInput,
  options: { dryRun?: boolean; notify?: boolean } = {},
) {
  const requestedWorkspaceId = Number(body.workspaceId ?? 0);
  if (body.workspaceId !== undefined && (!Number.isInteger(requestedWorkspaceId) || requestedWorkspaceId < 1)) {
    return NextResponse.json({ error: "Workspace tidak valid." }, { status: 400 });
  }
  const workspaceName = String(body.workspaceName ?? "Permintaan Data").trim();
  let source = String(body.csv ?? "");
  let googleSheetUrl = String(body.googleSheetUrl ?? "").trim();

  if (!workspaceName) {
    return NextResponse.json(
      { error: "Nama workspace wajib diisi." },
      { status: 400 },
    );
  }

  await ensureImportSchema();
  await ensureDataRequestMonitoringSchema();

  const [targets] = await db.query<DbRow[]>(`SELECT w.id FROM workspaces w
    LEFT JOIN workspace_members m ON m.workspace_id=w.id AND m.user_id=?
    WHERE ((? > 0 AND w.id=?) OR (?=0 AND LOWER(w.name)=LOWER(?)))
    AND (w.owner_id=? OR m.role IN ('administrator','manager'))
    ORDER BY (w.owner_id=?) DESC NULLS LAST,w.id LIMIT 1`,[userId,requestedWorkspaceId,requestedWorkspaceId,requestedWorkspaceId,workspaceName,userId,userId]);
  const targetId = Number(targets[0]?.id ?? 0);
  if (requestedWorkspaceId && !targetId) return NextResponse.json({ error: "Tidak punya akses ke workspace ini." }, { status: 403 });
  const configured = targetId ? await loadSourceSettings(targetId) : null;
  if (configured && (source || (googleSheetUrl && canonicalSheetUrl(googleSheetUrl) !== canonicalSheetUrl(configured.source_url)))) {
    return NextResponse.json({ error: "Ubah sumber melalui pengaturan Google Form agar pemetaan dan sinkronisasi awal diperiksa terlebih dahulu." }, { status: 400 });
  }
  if (configured?.paused) return NextResponse.json({ error: configured.last_error || "Sumber dijeda. Periksa pemetaan kolom." }, { status: 422 });
  const sourceVersion = configured?.version ?? null;
  const [previousSources] = targetId ? await db.query<DbRow[]>("SELECT google_sheet_url,last_synced_at FROM data_request_import_sources WHERE workspace_id=?", [targetId]) : [[]];
  const previousSourceUrl = previousSources[0]?.google_sheet_url ?? null;

  if (!source && !googleSheetUrl) {
    const [savedSources] = await db.query<DbRow[]>(
      `SELECT data_request_import_sources.google_sheet_url
       FROM workspaces
       LEFT JOIN workspace_members
         ON workspace_members.workspace_id = workspaces.id
        AND workspace_members.user_id = ?
       INNER JOIN data_request_import_sources
         ON data_request_import_sources.workspace_id = workspaces.id
       WHERE ((? > 0 AND workspaces.id = ?) OR (? = 0 AND LOWER(workspaces.name) = LOWER(?)))
         AND (
           workspaces.owner_id = ?
           OR workspace_members.role IN ('administrator', 'manager')
         )
       ORDER BY (workspaces.owner_id = ?) DESC NULLS LAST, workspaces.id ASC
       LIMIT 1`,
      [userId, requestedWorkspaceId, requestedWorkspaceId, requestedWorkspaceId, workspaceName, userId, userId],
    );
    googleSheetUrl = String(savedSources[0]?.google_sheet_url ?? "");
  }

  if (!source && googleSheetUrl) {
    try {
      const response = await fetch(googleSheetCsvUrl(googleSheetUrl), {
        cache: "no-store",
        signal: AbortSignal.timeout(20000),
      });
      if (!response.ok) {
        return NextResponse.json(
          {
            error:
              "Google Sheet tidak dapat dibaca. Pastikan aksesnya Anyone with the link.",
          },
          { status: 400 },
        );
      }
      source = await response.text();
    } catch {
      return NextResponse.json(
        { error: "URL Google Sheet tidak valid atau tidak dapat diakses." },
        { status: 400 },
      );
    }
  }

  if (!source.trim()) {
    return NextResponse.json(
      { error: "Masukkan URL Google Sheet atau unggah file CSV." },
      { status: 400 },
    );
  }

  let rows: DataRequestRow[];
  try {
    if (configured) {
      const parsed = readSpreadsheet(source);
      validateSettings(configured.settings, parsed.headers);
      const identities = new Set<string>();
      for (const row of parsed.rows.filter(row => row[configured.settings.mapping.title!]?.trim())) {
        const identity = mappedIdentity(row, configured.settings, canonicalSheetUrl(googleSheetUrl));
        if (identities.has(identity)) throw new Error("Identitas jawaban duplikat. Periksa pemetaan ID jawaban.");
        identities.add(identity);
      }
      rows = parsed.rows;
    } else rows = parseSpreadsheetText(source);
  } catch (error) {
    if (configured && !options.dryRun) await db.execute("UPDATE sheet_source_settings SET paused=1,last_error=? WHERE workspace_id=? AND version=?", [error instanceof Error ? error.message : "Struktur sheet berubah.", targetId, sourceVersion]);
    return NextResponse.json(
      { error: error instanceof Error ? error.message : "Format data tidak valid." },
      { status: 400 },
    );
  }

  const connection = await db.getConnection();
  const createdTaskIds: number[] = [];
  const createdTaskNotifications: Array<{
    taskId: number;
    projectId: number;
    taskName: string;
    projectName: string;
    requesterName: string;
    description: string;
    dueDate: string | Date | null;
    monitoringPath: string;
    customText?: string;
  }> = [];
  const monitoringLinks: Array<{
    taskId: number;
    taskName: string;
    requesterName: string;
    requesterEmail: string;
    path: string;
  }> = [];
  const skippedRows: Array<{ row: number; reason: string }> = [];
  let created = 0;
  let updated = 0;
  let skipped = 0;
  let projectsCreated = 0;

  const lockName = "clickme:data-request-import";
  try {
    const [locks] = await connection.query<DbRow[]>("SELECT pg_try_advisory_lock(hashtext(?)) AS acquired", [lockName]);
    if (!locks[0]?.acquired) return NextResponse.json({ error: "Sinkronisasi sedang berjalan." }, { status: 409 });
    const latest = targetId ? await loadSourceSettings(targetId) : null;
    const [currentSources] = targetId ? await connection.query<DbRow[]>("SELECT google_sheet_url FROM data_request_import_sources WHERE workspace_id=?", [targetId]) : [[]];
    if ((latest?.version ?? null) !== sourceVersion || (currentSources[0]?.google_sheet_url ?? null) !== previousSourceUrl) {
      return NextResponse.json({ error: "Sumber berubah selama proses. Sinkronisasi akan diulang." }, { status: 409 });
    }
    await connection.beginTransaction();

    const [workspaceRows] = await connection.query<DbRow[]>(
      `SELECT workspaces.id, workspaces.slug
       FROM workspaces
       LEFT JOIN workspace_members
         ON workspace_members.workspace_id = workspaces.id
        AND workspace_members.user_id = ?
       WHERE ((? > 0 AND workspaces.id = ?) OR (? = 0 AND LOWER(workspaces.name) = LOWER(?)))
         AND (
           workspaces.owner_id = ?
           OR workspace_members.role IN ('administrator', 'manager')
         )
       ORDER BY (workspaces.owner_id = ?) DESC NULLS LAST, workspaces.id ASC
       LIMIT 1`,
      [userId, requestedWorkspaceId, requestedWorkspaceId, requestedWorkspaceId, workspaceName, userId, userId],
    );

    let workspaceId = Number(workspaceRows[0]?.id ?? 0);
    let workspaceSlug = String(workspaceRows[0]?.slug ?? "");

    if (!workspaceId && requestedWorkspaceId) {
      await connection.rollback();
      return NextResponse.json({ error: "Tidak punya akses ke workspace ini." }, { status: 403 });
    }

    if (!workspaceId) {
      workspaceSlug = randomSlug(workspaceName, "permintaan-data");
      const [workspaceResult] = await connection.execute<DbResult>(
        `INSERT INTO workspaces (slug, owner_id, name, description)
         VALUES (?, ?, ?, ?)
         RETURNING id`,
        [
          workspaceSlug,
          userId,
          workspaceName,
          "Permintaan data yang diimpor dari spreadsheet.",
        ],
      );
      workspaceId = workspaceResult.insertId;
      await connection.execute(
        `INSERT INTO workspace_members (workspace_id, user_id, role)
         VALUES (?, ?, 'administrator')`,
        [workspaceId, userId],
      );
    }

    const projectCache = new Map<
      string,
      { id: number; statusId: number; slug: string; viewSlug: string }
    >();

    async function ensureProject(projectName: string) {
      const projectKey = projectName.toLocaleLowerCase("id-ID");
      const cachedProject = projectCache.get(projectKey);
      if (cachedProject) {
        return cachedProject;
      }

      const [projectRows] = await connection.query<DbRow[]>(
        `SELECT projects.id, projects.slug, projects.view_slug,
           project_statuses.id AS status_id
         FROM projects
         LEFT JOIN project_statuses
           ON project_statuses.project_id = projects.id
          AND project_statuses.category = 'not_started'
         WHERE projects.workspace_id = ?
           AND LOWER(projects.name) = LOWER(?)
         ORDER BY project_statuses.position ASC NULLS FIRST
         LIMIT 1`,
        [workspaceId, projectName],
      );

      let project: {
        id: number;
        statusId: number;
        slug: string;
        viewSlug: string;
      };

      if (projectRows[0]) {
        project = {
          id: Number(projectRows[0].id),
          statusId: Number(projectRows[0].status_id),
          slug: String(projectRows[0].slug),
          viewSlug: String(projectRows[0].view_slug),
        };
      } else {
        const slug = randomSlug(projectName, "kategori");
        const viewSlug = randomSlug("view", "view");
        const [projectResult] = await connection.execute<DbResult>(
          `INSERT INTO projects
            (workspace_id, owner_id, slug, view_slug, name, description, permission, is_private)
           VALUES (?, ?, ?, ?, ?, ?, 'Full akses', 0)
           RETURNING id`,
          [
            workspaceId,
            userId,
            slug,
            viewSlug,
            projectName,
            `Permintaan data kategori ${projectName}.`,
          ],
        );
        await connection.execute(
          `INSERT INTO project_members (project_id, user_id, permission)
           VALUES (?, ?, 'Full akses')`,
          [projectResult.insertId, userId],
        );
        const [statusResult] = await connection.execute<DbResult>(
          `INSERT INTO project_statuses
            (project_id, name, color, category, position, is_default)
           VALUES
             (?, 'TO DO', 'neutral', 'not_started', 1, 1),
             (?, 'IN PROGRESS', 'blue', 'active', 2, 1),
             (?, 'COMPLETE', 'green', 'closed', 3, 1)
           RETURNING id`,
          [projectResult.insertId, projectResult.insertId, projectResult.insertId],
        );
        project = {
          id: projectResult.insertId,
          statusId: statusResult.insertId,
          slug,
          viewSlug,
        };
        projectsCreated += 1;
      }

      if (!project.statusId) {
        const [statusResult] = await connection.execute<DbResult>(
          `INSERT INTO project_statuses
            (project_id, name, color, category, position, is_default)
           VALUES (?, 'TO DO', 'neutral', 'not_started', 1, 1)
           RETURNING id`,
          [project.id],
        );
        project.statusId = statusResult.insertId;
      }

      projectCache.set(projectKey, project);
      return project;
    }

    for (const projectName of configured ? [] : dataRequestProjectNames) {
      await ensureProject(projectName);
    }

    for (let rowIndex = 0; rowIndex < rows.length; rowIndex += 1) {
      const raw = rows[rowIndex];
      const row = configured ? mappedRow(raw, configured.settings) : raw;
      const rawTitle = configured ? (raw[configured.settings.mapping.title!] || "").trim() : "";
      const taskName = configured ? Array.from(rawTitle).slice(0, 180).join("") : buildRequestTaskName(row);
      const category = configured ? raw[configured.settings.mapping.category || ""]?.trim() : "";
      const projectName = configured ? (category || configured.settings.defaultProject).slice(0,100) : resolveDataRequestProjectName(row);

      if (!taskName) {
        skipped += 1;
        skippedRows.push({
          row: rowIndex + 2,
          reason: `Kolom "${dataRequestHeaders.fullName}", "${dataRequestHeaders.organization}", dan "${dataRequestHeaders.reason}" kosong.`,
        });
        continue;
      }

      for (const field of [dataRequestHeaders.fullName, dataRequestHeaders.email, dataRequestHeaders.contact]) {
        if (Array.from(getRowValue(row, field)).length > 191) throw new Error(`Baris ${rowIndex + 2}: ${field} melebihi 191 karakter.`);
      }
      const project = await ensureProject(projectName);

      const sourceKey = configured ? mappedIdentity(raw, configured.settings, canonicalSheetUrl(googleSheetUrl)) : dataRequestSourceKey(row);
      const legacyKey = dataRequestSourceKey(raw);
      const [importRows] = await connection.query<DbRow[]>(
        `SELECT task_id, project_id
         FROM data_request_import_rows
         WHERE workspace_id = ? AND source_key IN (?, ?)
         ORDER BY (source_key = ?) DESC LIMIT 1`,
        [workspaceId, sourceKey, configured ? legacyKey : sourceKey, sourceKey],
      );
      if (configured && importRows[0]) {
        await connection.execute("UPDATE data_request_import_rows SET source_key=? WHERE workspace_id=? AND task_id=?", [sourceKey, workspaceId, importRows[0].task_id]);
      }
      const description = configured ? mappedDescription(raw, configured.settings) : buildRequestDescription(row);
      const dueDate = requestDueDate(
        getRowValue(row, dataRequestHeaders.timestamp),
      );
      const sourceTimestamp = parseRequestTimestamp(
        getRowValue(row, dataRequestHeaders.timestamp),
      );
      const taskId = Number(importRows[0]?.task_id ?? 0);
      const previousProjectId = Number(importRows[0]?.project_id ?? 0);
      let importedTaskId = taskId;
      let taskWasCreated = false;

      if (taskId) {
        let updateResult: DbResult;

        if (previousProjectId !== project.id) {
          [updateResult] = await connection.execute<DbResult>(
            `UPDATE tasks
             SET project_id = ?, status_id = ?, name = ?, due_date = ?,
                 priority = 'Urgent', description = ?
             WHERE id = ?
               AND (project_id IS DISTINCT FROM ? OR status_id IS DISTINCT FROM ? OR name IS DISTINCT FROM ?
                 OR due_date IS DISTINCT FROM ? OR priority IS DISTINCT FROM 'Urgent' OR description IS DISTINCT FROM ?)`,
            [project.id, project.statusId, taskName, dueDate, description, taskId, project.id, project.statusId, taskName, dueDate, description],
          );
        } else {
          [updateResult] = await connection.execute<DbResult>(
            `UPDATE tasks
             SET name = ?, due_date = ?, priority = 'Urgent', description = ?
             WHERE id = ?
               AND (name IS DISTINCT FROM ? OR due_date IS DISTINCT FROM ? OR priority IS DISTINCT FROM 'Urgent'
                 OR description IS DISTINCT FROM ?)`,
            [taskName, dueDate, description, taskId, taskName, dueDate, description],
          );
        }
        await connection.execute(
          `UPDATE data_request_import_rows
           SET project_id = ?, source_timestamp = ?, source_row = ?
           WHERE workspace_id = ? AND source_key = ?`,
          [
            project.id,
            sourceTimestamp,
            rowIndex + 2,
            workspaceId,
            sourceKey,
          ],
        );
        if (updateResult.affectedRows > 0) {
          updated += 1;
        }
      } else {
        const [taskResult] = await connection.execute<DbResult>(
          `INSERT INTO tasks
            (project_id, status_id, name, assignee_id, start_date, due_date, priority, description)
           VALUES (?, ?, ?, NULL, NULL, ?, 'Urgent', ?)
           RETURNING id`,
          [project.id, project.statusId, taskName, dueDate, description],
        );
        await connection.execute(
          `INSERT INTO data_request_import_rows
            (workspace_id, project_id, task_id, source_key, source_timestamp, source_row)
           VALUES (?, ?, ?, ?, ?, ?)`,
          [
            workspaceId,
            project.id,
            taskResult.insertId,
            sourceKey,
            sourceTimestamp,
            rowIndex + 2,
          ],
        );
        createdTaskIds.push(taskResult.insertId);
        importedTaskId = taskResult.insertId;
        taskWasCreated = true;
        created += 1;
      }

      const monitoringToken = createMonitoringToken();
      await connection.execute(
        `INSERT INTO data_request_public_access
          (task_id, public_token, requester_name, requester_email, requester_contact)
         VALUES (?, ?, ?, ?, ?)
         ON CONFLICT (task_id) DO UPDATE SET
           requester_name = EXCLUDED.requester_name,
           requester_email = EXCLUDED.requester_email,
           requester_contact = EXCLUDED.requester_contact`,
        [
          importedTaskId,
          monitoringToken,
          getRowValue(row, dataRequestHeaders.fullName) || null,
          getRowValue(row, dataRequestHeaders.email) || null,
          getRowValue(row, dataRequestHeaders.contact) || null,
        ],
      );
      const [accessRows] = await connection.query<DbRow[]>(
        `SELECT public_token
         FROM data_request_public_access
         WHERE task_id = ?
         LIMIT 1`,
        [importedTaskId],
      );
      const monitoringPath = `/monitoring/${String(
        accessRows[0]?.public_token ?? monitoringToken,
      )}`;
      const requesterName =
        getRowValue(row, dataRequestHeaders.fullName) || "Pemohon";

      monitoringLinks.push({
        taskId: importedTaskId,
        taskName,
        requesterName,
        requesterEmail: getRowValue(row, dataRequestHeaders.email),
        path: monitoringPath,
      });

      if (taskWasCreated) {
        createdTaskNotifications.push({
          customText: configured ? renderSheetMessage(configured.settings.template, raw, configured.settings) : undefined,
          taskId: importedTaskId,
          projectId: project.id,
          taskName,
          projectName,
          requesterName,
          description,
          dueDate,
          monitoringPath,
        });
      }
    }

    if (googleSheetUrl) {
      await connection.execute(
        `INSERT INTO data_request_import_sources
          (workspace_id, google_sheet_url, last_synced_at)
         VALUES (?, ?, NOW())
         ON CONFLICT (workspace_id) DO UPDATE SET
           google_sheet_url = EXCLUDED.google_sheet_url,
           last_synced_at = EXCLUDED.last_synced_at`,
        [workspaceId, googleSheetUrl],
      );
    }

    if (options.dryRun) {
      await connection.rollback();
      return NextResponse.json({ dryRun: true, summary: { rows: rows.length, created, updated, skipped, projectsCreated } });
    }

    const initialSync = configured ? Boolean(configured.initial_pending) : !previousSources[0]?.last_synced_at || Boolean(googleSheetUrl && previousSourceUrl && canonicalSheetUrl(googleSheetUrl) !== canonicalSheetUrl(previousSourceUrl));
    if (configured) await connection.execute("UPDATE sheet_source_settings SET initial_pending=0,last_error=NULL WHERE workspace_id=? AND version=?", [workspaceId, sourceVersion]);
    for (const task of options.notify === false || initialSync ? [] : createdTaskNotifications) {
      await connection.execute(
        "INSERT INTO sheet_notification_queue (task_id, payload) VALUES (?, ?) ON CONFLICT DO NOTHING",
        [task.taskId, JSON.stringify({ ...task, workspaceName, priority: "Urgent" })],
      );
    }

    await connection.commit();

    await Promise.allSettled(
      createdTaskIds.map((taskId) =>
        recordTaskActivity({
          taskId,
          userId,
          type: "created",
          message: "created this task from Google Sheet",
        }),
      ),
    );

    const whatsapp = options.notify === false
      ? { sent: 0, failed: 0, skipped: 0 }
      : await flushSheetNotifications();

    return NextResponse.json({
      workspace: { id: workspaceId, name: workspaceName, slug: workspaceSlug },
      summary: {
        rows: rows.length,
        created,
        updated,
        skipped,
        skippedRows,
        projectsCreated,
      },
      whatsapp,
      monitoringLinks,
    });
  } catch (error) {
    await connection.rollback();
    if (configured && !options.dryRun) await db.execute("UPDATE sheet_source_settings SET paused=1,last_error=? WHERE workspace_id=? AND version=?", [error instanceof Error && error.message.startsWith("Baris ") ? error.message : "Impor gagal. Periksa panjang data dan pemetaan, lalu simpan ulang untuk melanjutkan.", targetId, sourceVersion]);
    console.error("Data request import failed", { code: (error as { code?: string }).code || "IMPORT_ERROR" });
    return NextResponse.json(
      { error: "Impor gagal diproses. Periksa format dan struktur database." },
      { status: 500 },
    );
  } finally {
    await connection.query("SELECT pg_advisory_unlock(hashtext(?))", [lockName]);
    connection.release();
  }
}
